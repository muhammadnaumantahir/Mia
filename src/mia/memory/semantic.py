"""Optional local-only semantic reranking for persistent memory.

Embeddings are generated by an owner-configured Ollama model on loopback. No
cloud embedding provider, credentials, or remote network destination is used.
If the local service is unavailable, callers fall back to lexical retrieval.
"""
from __future__ import annotations

import math
import os
from collections.abc import Callable, Sequence
from urllib.parse import urlsplit
from typing import Any

import httpx

from mia.gateway.urlpolicy import validate_provider_url

Embedder = Callable[[list[str]], list[list[float]]]


def _record_key(record: dict[str, Any]) -> str:
    for key in ("record_id", "item_id", "message_id"):
        value = record.get(key)
        if isinstance(value, str) and value:
            return value
    return ""


def _record_text(record: dict[str, Any]) -> str:
    title = str(record.get("title") or "")
    body = str(record.get("body") or record.get("content") or "")
    return (title + "\n" + body)[:6000]


def _cosine(left: Sequence[float], right: Sequence[float]) -> float:
    if not left or len(left) != len(right):
        raise ValueError("embedding vectors must have the same non-zero dimensions")
    dot = sum(a * b for a, b in zip(left, right, strict=True))
    left_norm = math.sqrt(sum(a * a for a in left))
    right_norm = math.sqrt(sum(b * b for b in right))
    if left_norm <= 0 or right_norm <= 0:
        raise ValueError("embedding vector has zero magnitude")
    score = dot / (left_norm * right_norm)
    if not math.isfinite(score):
        raise ValueError("embedding similarity is not finite")
    return max(-1.0, min(1.0, score))


class LocalOllamaEmbeddingReranker:
    """Semantic score boosts using a loopback-only Ollama /api/embed endpoint."""

    def __init__(
        self,
        *,
        model: str,
        base_url: str = "http://127.0.0.1:11434",
        timeout_seconds: float = 8.0,
        embedder: Embedder | None = None,
    ) -> None:
        model = model.strip()
        if not model or len(model) > 120 or any(ch in model for ch in "\r\n\0"):
            raise ValueError("a valid local embedding model name is required")
        clean_url = validate_provider_url(base_url, allow_private=True)
        parts = urlsplit(clean_url)
        if parts.scheme != "http" or parts.hostname not in {"127.0.0.1", "localhost", "::1"}:
            raise ValueError("memory embeddings must use a loopback-only HTTP Ollama endpoint")
        if not math.isfinite(timeout_seconds) or not 1.0 <= timeout_seconds <= 60.0:
            raise ValueError("embedding timeout must be between 1 and 60 seconds")
        self.model = model
        self.base_url = clean_url
        self.timeout_seconds = timeout_seconds
        self._embedder = embedder

    @classmethod
    def from_env(cls) -> "LocalOllamaEmbeddingReranker | None":
        if os.getenv("MIA_MEMORY_SEMANTIC_RERANK_ENABLED", "false").strip().lower() != "true":
            return None
        model = os.getenv("MIA_MEMORY_EMBEDDING_MODEL", "").strip()
        if not model:
            return None
        return cls(
            model=model,
            base_url=os.getenv("MIA_OLLAMA_BASE_URL", "http://127.0.0.1:11434"),
        )

    def _embed(self, texts: list[str]) -> list[list[float]]:
        if self._embedder is not None:
            vectors = self._embedder(texts)
        else:
            response = httpx.post(
                f"{self.base_url}/api/embed",
                json={"model": self.model, "input": texts},
                timeout=self.timeout_seconds,
            )
            response.raise_for_status()
            payload = response.json()
            vectors = payload.get("embeddings") if isinstance(payload, dict) else None
        if not isinstance(vectors, list) or len(vectors) != len(texts):
            raise ValueError("local embedding service returned an invalid batch")
        clean: list[list[float]] = []
        dimensions: int | None = None
        for vector in vectors:
            if not isinstance(vector, list) or not vector:
                raise ValueError("local embedding service returned an empty vector")
            values = [float(value) for value in vector]
            if not all(math.isfinite(value) for value in values):
                raise ValueError("local embedding service returned a non-finite vector")
            if dimensions is None:
                dimensions = len(values)
            elif len(values) != dimensions:
                raise ValueError("local embedding vectors have inconsistent dimensions")
            clean.append(values)
        return clean

    def __call__(self, query: str, records: list[dict[str, Any]]) -> dict[str, float]:
        selected = [(key, _record_text(record)) for record in records
                    if (key := _record_key(record)) and _record_text(record).strip()]
        if not selected:
            return {}
        vectors = self._embed([query[:6000], *(text for _, text in selected)])
        query_vector = vectors[0]
        similarities = [
            (key, _cosine(query_vector, vector))
            for (key, _), vector in zip(selected, vectors[1:], strict=True)
        ]
        # Only positively similar records receive a boost. The caller clamps the
        # result to its global ±0.3 reranking safety bound.
        return {key: max(0.0, min(0.3, (score - 0.35) * 0.6))
                for key, score in similarities}
